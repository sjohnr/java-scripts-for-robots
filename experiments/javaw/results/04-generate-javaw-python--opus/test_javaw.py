"""Tests for javaw. Run: python3 -m unittest -v test_javaw.py"""
import os, runpy, shutil, subprocess, tempfile, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
JAVAW = os.path.join(HERE, "javaw")
HELLO = os.path.join(HERE, "examples", "Hello.java")
kebab = runpy.run_path(JAVAW)["kebab"]
HAS_JAVA = shutil.which("java") is not None


def run(cmd, cwd, env=None):
    return subprocess.run(cmd, cwd=cwd, env={**os.environ, **(env or {})},
                          capture_output=True, text=True)


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = os.path.realpath(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)

    def path(self, *p):
        return os.path.join(self.tmp, *p)

    def touch(self, name, text=""):
        os.makedirs(os.path.dirname(self.path(name)), exist_ok=True)
        with open(self.path(name), "w") as f:
            f.write(text)

    def javaw(self, *args, ok=True):
        r = run([JAVAW, *args], self.tmp)
        self.assertEqual(r.returncode == 0, ok, r.stderr)
        return r

    def read(self, name):
        with open(self.path(name)) as f:
            return f.read()


class KebabTest(unittest.TestCase):
    def test_rules(self):
        for given, want in [("FooBar", "foo-bar"), ("HTTPServer", "http-server"),
                            ("Example1_Assert", "example1-assert"), ("Example1", "example1"),
                            ("Foo__Bar", "foo-bar"), ("my-tool", "my-tool"), ("Tool", "tool"),
                            ("my.tool name", "my-tool-name"), ("parseJSONFile", "parse-json-file")]:
            self.assertEqual(kebab(given), want, given)


class GenerateTest(Base):
    def test_default_names(self):
        self.touch("Tool.java"); self.touch("my-tool.jar")
        self.javaw("Tool.java")
        self.javaw("--jar", "my-tool.jar")
        self.assertTrue(os.access(self.path("run-tool"), os.X_OK))
        self.assertTrue(os.access(self.path("run-my-tool"), os.X_OK))

    def test_source_wrapper_is_minimal(self):
        self.touch("Tool.java")
        self.javaw("Tool.java")
        w = self.read("run-tool")
        self.assertTrue(w.startswith("#!/bin/sh\n# Generated by: javaw Tool.java\n"))
        self.assertIn('exec java "$dir/Tool.java" "$@"', w)
        for unused in ("-cp", "-jar", "version", "[[", "readlink -f", "realpath"):
            self.assertNotIn(unused, w)

    def test_all_options(self):
        self.touch("tool.jar")
        self.javaw("--jar", "--classpath", "lib/*", "--java-home", "/opt/my jdk",
                   "--jvm-opts", "-Xmx1g -Dk='a b'", "--min-java", "17", "tool.jar")
        w = self.read("run-tool")
        self.assertIn("exec '/opt/my jdk/bin/java' -cp 'lib/*' -Xmx1g '-Dk=a b' "
                      '-jar "$dir/tool.jar" "$@"', w)
        self.assertIn("found=$('/opt/my jdk/bin/java' -version", w)
        self.assertIn('"$major" -lt 17', w)
        self.assertIn("# Generated by: javaw --jar --classpath 'lib/*' --java-home '/opt/my jdk' "
                      "--jvm-opts '-Xmx1g -Dk='\"'\"'a b'\"'\"'' --min-java 17 tool.jar\n", w)

    def test_header_command_regenerates_same_wrapper(self):
        self.touch("Tool.java")
        self.javaw("--jvm-opts", "-Dk='a b' -Dx=$HOME", "-o", "out file", "Tool.java")
        first = self.read("out file")
        cmd = first.splitlines()[1].removeprefix("# Generated by: javaw ")
        r = run(["sh", "-c", '"$0" ' + cmd + " --force", JAVAW], self.tmp)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(self.read("out file").split("\n", 2)[2], first.split("\n", 2)[2])

    def test_output_name_and_paths(self):
        self.touch("src/Tool.java")
        self.javaw("-o", "bin/tool", "src/Tool.java")
        self.assertIn('"$dir/../src/Tool.java"', self.read("bin/tool"))
        self.javaw("-o", "out/", "src/Tool.java")
        self.assertTrue(os.path.exists(self.path("out", "run-tool")))
        self.javaw("-o", "bin", "src/Tool.java")  # existing directory
        self.assertTrue(os.path.exists(self.path("bin", "run-tool")))

    def test_several_inputs(self):
        self.touch("FooBar.java"); self.touch("HTTPServer.java")
        self.javaw("FooBar.java", "HTTPServer.java")
        self.assertTrue(os.path.exists(self.path("run-foo-bar")))
        self.assertTrue(os.path.exists(self.path("run-http-server")))
        self.javaw("-o", "bin/", "FooBar.java", "HTTPServer.java")
        self.assertTrue(os.path.exists(self.path("bin", "run-http-server")))
        r = self.javaw("-o", "single", "FooBar.java", "HTTPServer.java", ok=False)
        self.assertIn("must be a directory", r.stderr)

    def test_refuses_overwrite_without_force(self):
        self.touch("Tool.java"); self.touch("run-tool", "keep me")
        r = self.javaw("Tool.java", ok=False)
        self.assertIn("--force", r.stderr)
        self.assertEqual(self.read("run-tool"), "keep me")
        self.javaw("--force", "Tool.java")
        self.assertIn("exec java", self.read("run-tool"))

    def test_cli_errors(self):
        self.touch("Tool.java")
        self.assertIn("required: INPUT", self.javaw(ok=False).stderr)
        self.assertIn("unrecognized arguments: --bogus", self.javaw("--bogus", "Tool.java", ok=False).stderr)
        self.assertIn("input not found", self.javaw("Nope.java", ok=False).stderr)
        self.assertIn("invalid int", self.javaw("--min-java", "x", "Tool.java", ok=False).stderr)
        self.assertIn("--min-java", self.javaw("--help").stdout)
        self.assertIn("--jvm-opts: expected one argument",self.javaw("Tool.java", "--jvm-opts", ok=False).stderr)

    def test_option_values_starting_with_dash(self):
        self.touch("Tool.java")
        self.javaw("--jvm-opts", "-Xmx1g", "-o", "-weird", "Tool.java")
        self.assertIn('exec java -Xmx1g "$dir/Tool.java" "$@"', self.read("-weird"))


class VersionCheckTest(Base):
    """Runs the min-java check against fake JVMs, so no real Java is needed."""

    def check(self, version_output, min_java="11"):
        self.touch("jdk/bin/java", "#!/bin/sh\nif [ \"$1\" = -version ]; then\n"
                   "cat >&2 <<'EOF'\n%sEOF\nelse echo launched; fi\n" % version_output)
        os.chmod(self.path("jdk/bin/java"), 0o755)
        self.touch("Tool.java")
        self.javaw("--force", "--java-home", self.path("jdk"), "--min-java", min_java, "Tool.java")
        return run([self.path("run-tool")], self.tmp)

    def test_parses_versions(self):
        notice = "Picked up JAVA_TOOL_OPTIONS: -Dversion=\"99\"\n"
        for out, ok in [('openjdk version "28-ea" 2027-03-23\n', True),
                        ('java version "1.8.0_401"\n', False),
                        (notice + 'openjdk version "11.0.2" 2019-01-15\n', True),
                        (notice + 'openjdk version "10" 2018-03-20\n', False)]:
            r = self.check(out)
            self.assertEqual(r.returncode == 0, ok, out + r.stderr)
            if not ok:
                self.assertIn("error: Java 11 or newer is required", r.stderr)

    def test_unparseable_or_missing_java(self):
        r = self.check("garbage\n")
        self.assertEqual(r.returncode, 1)
        self.assertEqual(r.stderr, "error: Java 11 or newer is required (found: no usable java)\n")
        os.remove(self.path("jdk/bin/java"))
        r = run([self.path("run-tool")], self.tmp)
        self.assertEqual(r.returncode, 1)
        self.assertIn("error: Java 11 or newer is required (found: no usable java)", r.stderr)


@unittest.skipUnless(HAS_JAVA, "java not on PATH")
class EndToEndTest(Base):
    """Generates wrappers for examples/Hello.java and runs them for real."""

    def setUp(self):
        super().setUp()
        os.makedirs(self.path("app", "bin"))
        os.makedirs(self.path("elsewhere"))
        shutil.copy(HELLO, self.path("app"))
        r = run([JAVAW, "--min-java", "11", "-o", "bin/", "Hello.java"], self.path("app"))
        self.assertEqual(r.returncode, 0, r.stderr)
        self.wrapper = self.path("app", "bin", "run-hello")

    def assertHello(self, cmd, cwd, env=None, want="Hello a b (app.version=1)\n"):
        r = run(cmd + ["a", "b"], cwd, env)
        self.assertEqual((r.returncode, r.stdout), (0, want), r.stderr)

    def test_from_another_directory(self):
        self.assertHello([self.wrapper], self.path("elsewhere"))
        self.assertHello(["../app/bin/run-hello"], self.path("elsewhere"))

    def test_moved_and_renamed_with_siblings(self):
        os.rename(self.path("app"), self.path("-moved"))
        os.rename(self.path("-moved", "bin", "run-hello"), self.path("-moved", "bin", "hi"))
        self.assertHello(["./-moved/bin/hi"], self.tmp)

    def test_relative_symlink(self):
        os.symlink("../app/bin/run-hello", self.path("elsewhere", "hello"))
        self.assertHello(["./hello"], self.path("elsewhere"))

    def test_symlink_chain_of_two(self):
        os.makedirs(self.path("links", "deeper"))
        os.symlink("../../app/bin/run-hello", self.path("links", "deeper", "one"))
        os.symlink("deeper/one", self.path("links", "two"))
        self.assertHello([self.path("links", "two")], self.path("elsewhere"))
        self.assertHello(["../links/two"], self.path("elsewhere"))

    def test_java_tool_options(self):
        self.assertHello([self.wrapper], self.path("elsewhere"),
                         {"JAVA_TOOL_OPTIONS": "-Dapp.version=2"}, "Hello a b (app.version=2)\n")

    def test_cdpath(self):
        # "bin" matches a CDPATH entry that contains a decoy bin/ directory.
        os.makedirs(self.path("elsewhere", "bin"))
        env = {"CDPATH": self.path("elsewhere")}
        self.assertHello(["bin/run-hello"], self.path("app"), env)

    def test_posix_shells(self):
        for sh in ("dash", "sh", "bash"):
            if shutil.which(sh):
                self.assertHello([sh, self.wrapper], self.path("elsewhere"))

    def test_jar_launch(self):
        if not (shutil.which("javac") and shutil.which("jar")):
            self.skipTest("javac/jar not on PATH")
        app = self.path("app")
        for cmd in (["javac", "-d", "classes", "Hello.java"],
                    ["jar", "--create", "--file", "hello.jar", "--main-class", "Hello", "-C", "classes", "."],
                    [JAVAW, "--jar", "--jvm-opts", "-Dapp.version=3", "-o", "bin/", "hello.jar", "--force"]):
            r = run(cmd, app)
            self.assertEqual(r.returncode, 0, r.stderr)
        os.symlink("../app/bin/run-hello", self.path("elsewhere", "hello"))
        self.assertHello(["./hello"], self.path("elsewhere"), want="Hello a b (app.version=3)\n")


if __name__ == "__main__":
    unittest.main()
