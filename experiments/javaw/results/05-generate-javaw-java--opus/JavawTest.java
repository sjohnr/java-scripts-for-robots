import java.io.*;
import java.nio.file.*;
import java.util.*;

/** Run from this directory: java JavawTest.java */
public class JavawTest {
    static int passed, failed;
    static Path tmp;

    static void check(boolean ok, String what) {
        if (ok) passed++; else { failed++; System.out.println("FAIL: " + what); }
    }
    static void eq(Object want, Object got, String what) {
        check(Objects.equals(want, got), what + "\n  want: " + want + "\n  got:  " + got);
    }

    static void gen(Path cwd, String... args) throws IOException {
        Javaw.run(args, cwd, new PrintStream(OutputStream.nullOutputStream()));
    }
    static String genFails(Path cwd, String... args) {
        try { gen(cwd, args); return null; } catch (Javaw.Fail | IOException e) { return e.getMessage(); }
    }

    /** Runs a shell command in cwd with extra env vars; returns "exit|stdout|stderr". */
    static String sh(Path cwd, String cmd, String... env) throws Exception {
        var pb = new ProcessBuilder("/bin/sh", "-c", cmd).directory(cwd.toFile());
        for (int i = 0; i < env.length; i += 2) pb.environment().put(env[i], env[i + 1]);
        Process p = pb.start();
        String out = new String(p.getInputStream().readAllBytes()).trim();
        String err = new String(p.getErrorStream().readAllBytes()).trim();
        return p.waitFor() + "|" + out + "|" + err;
    }
    static String stdout(Path cwd, String cmd, String... env) throws Exception {
        String r = sh(cwd, cmd, env);
        return r.split("\\|", -1)[1];
    }

    public static void main(String[] a) throws Exception {
        // Kebab-case naming
        eq("foo-bar", Javaw.kebab("FooBar"), "kebab FooBar");
        eq("http-server", Javaw.kebab("HTTPServer"), "kebab HTTPServer");
        eq("example1-assert", Javaw.kebab("Example1_Assert"), "kebab Example1_Assert");
        eq("example1", Javaw.kebab("Example1"), "kebab Example1");
        eq("foo-bar", Javaw.kebab("Foo__Bar"), "kebab Foo__Bar");
        eq("my-tool", Javaw.kebab("my-tool"), "kebab my-tool");
        eq("a-b-c", Javaw.kebab("a.b c"), "kebab separators");

        // Shell quoting
        eq("plain/path.jar", Javaw.sq("plain/path.jar"), "sq plain");
        eq("'a b'", Javaw.sq("a b"), "sq space");
        eq("'it'\\''s'", Javaw.sq("it's"), "sq quote");
        eq("''", Javaw.sq(""), "sq empty");

        tmp = Files.createTempDirectory("javaw-test").toRealPath();
        Path app = Files.createDirectories(tmp.resolve("app"));
        Files.copy(Path.of("examples/Hello.java"), app.resolve("Hello.java"));

        // Source launch: minimal content, executable, header
        gen(app, "Hello.java");
        Path w = app.resolve("run-hello");
        String text = Files.readString(w);
        check(Files.isExecutable(w), "wrapper is executable");
        check(text.startsWith("#!/bin/sh\n# Generated by: javaw Hello.java\n"), "shebang and header:\n" + text);
        check(text.contains("exec java \"$dir/Hello.java\" \"$@\""), "source launch line:\n" + text);
        check(!text.contains("version") && !text.contains("-cp") && !text.contains("[["), "wrapper is minimal");

        // Running: from another directory, through symlinks, with JAVA_TOOL_OPTIONS and CDPATH
        Path other = Files.createDirectories(tmp.resolve("other"));
        eq("hello a b,c version=1", stdout(other, "../app/run-hello 'a b' c"), "run from another directory");
        Path bin = Files.createDirectories(tmp.resolve("bin"));
        Files.createSymbolicLink(bin.resolve("hello"), Path.of("../app/run-hello"));
        Files.createSymbolicLink(bin.resolve("hello2"), Path.of("hello"));
        eq("hello x version=1", stdout(other, "../bin/hello x"), "run through relative symlink");
        eq("hello x version=1", stdout(other, "../bin/hello2 x"), "run through chain of two symlinks");
        eq("hello  version=1", stdout(tmp, "PATH=\"$PWD/bin:$PATH\" hello2 ''"), "run through PATH");
        eq("hello t version=2", stdout(other, "../app/run-hello t", "JAVA_TOOL_OPTIONS", "-Dapp.version=2"),
                "JAVA_TOOL_OPTIONS");
        Files.createDirectories(tmp.resolve("decoy/app"));
        eq("hello cd version=1", stdout(tmp, "export CDPATH=" + tmp.resolve("decoy") + "; app/run-hello cd"), "CDPATH exported");
        Path dash = Files.createDirectories(tmp.resolve("-dash"));
        Files.copy(app.resolve("Hello.java"), dash.resolve("Hello.java"));
        gen(dash, "Hello.java");
        eq("hello d version=1", stdout(tmp, "sh -- -dash/run-hello d"), "path starting with -");
        Files.move(app, tmp.resolve("moved"));
        eq("hello m version=1", stdout(tmp, "moved/run-hello m"), "relocated directory");
        Files.move(tmp.resolve("moved"), app);

        // JVM options, classpath and header quoting
        gen(app, "--jvm-opts", "-Dapp.version=3 -Xmx64m", "--classpath", "lib/*", "-o", "run-opts", "Hello.java");
        text = Files.readString(app.resolve("run-opts"));
        check(text.contains("# Generated by: javaw --jvm-opts '-Dapp.version=3 -Xmx64m' --classpath 'lib/*' -o run-opts Hello.java\n"), "header:\n" + text);
        check(text.contains("exec java -Dapp.version=3 -Xmx64m -cp 'lib/*' \"$dir/Hello.java\""), "opts line:\n" + text);
        eq("hello t version=3", stdout(other, "../app/run-opts t"), "jvm opts applied");

        // Jar launch
        sh(app, "javac -d classes Hello.java && jar --create --file hello.jar --main-class Hello -C classes .");
        gen(app, "--jar", "hello.jar", "-o", "bin/");
        text = Files.readString(app.resolve("bin/run-hello"));
        check(text.contains("exec java -jar \"$dir/../hello.jar\" \"$@\""), "jar launch line:\n" + text);
        eq("hello j version=1", stdout(other, "../app/bin/run-hello j"), "jar wrapper runs");

        // Minimum Java version, with the real JVM and fake ones
        gen(app, "--min-java", "8", "-o", "run-min8", "Hello.java");
        eq("hello t version=2", stdout(other, "../app/run-min8 t", "JAVA_TOOL_OPTIONS", "-Dapp.version=2"),
                "min-java passes with JAVA_TOOL_OPTIONS notice");
        gen(app, "--min-java", "999", "-o", "run-min999", "Hello.java");
        String r = sh(other, "../app/run-min999");
        check(r.startsWith("1||error: this program requires Java 999 or newer, but found: "), "min-java too new: " + r);
        Path fake = Files.createDirectories(tmp.resolve("fakejdk/bin"));
        Files.writeString(fake.resolve("java"), """
            #!/bin/sh
            echo 'Picked up JAVA_TOOL_OPTIONS: -Dx="version 9"' >&2
            echo "openjdk version \\"$FAKE\\" 2027-03-23" >&2
            echo "fake java $*"
            """);
        fake.resolve("java").toFile().setExecutable(true);
        gen(app, "--java-home", tmp.resolve("fakejdk/").toString(), "--min-java", "11", "-o", "run-fake", "Hello.java");
        eq("1||error: this program requires Java 11 or newer, but found: 1.8.0_392", sh(other, "../app/run-fake", "FAKE", "1.8.0_392"), "1.8 is 8");
        check(sh(other, "../app/run-fake z", "FAKE", "28-ea").startsWith("0|fake java " + app + "/Hello.java z|"), "28-ea is 28, java-home used");
        eq("1||error: this program requires Java 11 or newer, but found: bogus", sh(other, "../app/run-fake", "FAKE", "bogus"), "unparseable");
        gen(app, "--java-home", "/nonexistent", "--min-java", "11", "-o", "run-none", "Hello.java");
        eq("1||error: this program requires Java 11 or newer, but found: no usable Java", sh(other, "../app/run-none"), "missing java");

        // Several inputs, output directories, overwriting
        Files.writeString(app.resolve("HTTPServer.java"), "class HTTPServer {}");
        gen(app, "Hello.java", "HTTPServer.java", "-o", "out/");
        check(Files.exists(app.resolve("out/run-hello")) && Files.exists(app.resolve("out/run-http-server")), "several inputs into out/");
        Files.createDirectories(app.resolve("out2"));
        gen(app, "HTTPServer.java", "-o", "out2");
        check(Files.exists(app.resolve("out2/run-http-server")), "-o existing directory");
        check(genFails(app, "Hello.java").contains("already exists"), "refuses to overwrite");
        gen(app, "--force", "Hello.java");
        check(genFails(app, "Hello.java", "HTTPServer.java", "-o", "one-file").contains("must be a directory"), "-o file with several inputs");

        // CLI errors
        check(genFails(app, "--nope", "Hello.java").contains("unknown option: --nope"), "unknown option");
        check(genFails(app).contains("missing input"), "missing input");
        check(genFails(app, "Missing.java").contains("input not found"), "input not found");
        check(genFails(app, "--min-java", "x", "Hello.java").contains("version number"), "bad --min-java");
        check(genFails(app, "Hello.java", "-o").contains("requires a value"), "missing option value");
        var help = new ByteArrayOutputStream();
        eq(0, Javaw.run(new String[] {"--help"}, app, new PrintStream(help)), "help exit code");
        check(help.toString().startsWith("Usage: javaw"), "help text");

        System.out.println(passed + " passed, " + failed + " failed (temp dir: " + tmp + ")");
        System.exit(failed == 0 ? 0 : 1);
    }
}
