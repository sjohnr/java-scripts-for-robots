'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const { kebab, defaultName, quote } = require('../javaw');

const JAVAW = path.resolve(__dirname, '../javaw');
const HELLO = path.resolve(__dirname, '../examples/Hello.java');
const has = (cmd) => spawnSync('sh', ['-c', `command -v ${cmd}`]).status === 0;

const tmp = () => fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'javaw-')));
const run = (cmd, args, opts = {}) => spawnSync(cmd, args, { encoding: 'utf8', ...opts });
const javaw = (cwd, ...args) => run(process.execPath, [JAVAW, ...args], { cwd });
const read = (p) => fs.readFileSync(p, 'utf8');
const touch = (p, s = '') => (fs.mkdirSync(path.dirname(p), { recursive: true }), fs.writeFileSync(p, s));

// A fake JDK whose java prints a given -version banner, or echoes its arguments.
function fakeJdk(dir, banner) {
  touch(path.join(dir, 'bin/java'), `#!/bin/sh
if [ "$1" = -version ]; then printf '%s\\n' ${banner.map(quote).join(' ')} >&2; exit 0; fi
for a in "$@"; do printf '[%s]' "$a"; done; echo\n`);
  fs.chmodSync(path.join(dir, 'bin/java'), 0o755);
  return dir;
}

test('kebab-case default names', () => {
  for (const [input, want] of [['FooBar', 'foo-bar'], ['HTTPServer', 'http-server'],
    ['Example1_Assert', 'example1-assert'], ['Example1', 'example1'], ['Foo__Bar', 'foo-bar'],
    ['my tool', 'my-tool'], ['a.b', 'a-b'], ['my-tool', 'my-tool']]) {
    assert.equal(kebab(input), want, input);
  }
  assert.equal(defaultName('my-tool.jar'), 'run-my-tool');
  assert.equal(defaultName('src/Tool.java'), 'run-tool');
  assert.equal(defaultName('tool.jar'), 'run-tool');
});

test('shell quoting', () => {
  assert.equal(quote('Tool.java'), 'Tool.java');
  assert.equal(quote('a b'), `'a b'`);
  assert.equal(quote(`it's`), `'it'\\''s'`);
  assert.equal(quote(''), `''`);
});

test('CLI help and errors', () => {
  const d = tmp();
  const help = javaw(d, '--help');
  assert.equal(help.status, 0);
  assert.match(help.stdout, /Usage: javaw/);
  assert.match(javaw(d, '--bogus').stderr, /unknown option: --bogus/);
  assert.equal(javaw(d, '--bogus').status, 2);
  assert.match(javaw(d).stderr, /missing input file/);
  assert.match(javaw(d, '--jar').stderr, /--jar requires a value/);
  assert.match(javaw(d, 'Nope.java').stderr, /Nope.java: no such file/);
  touch(path.join(d, 't.jar'));
  assert.match(javaw(d, 't.jar').stderr, /use --jar/);
  touch(path.join(d, 'T.java'));
  assert.match(javaw(d, '--min-java', 'x', 'T.java').stderr, /positive integer/);
});

test('source and jar wrappers: content, mode, header, minimal', () => {
  const d = tmp();
  touch(path.join(d, 'Tool.java'));
  touch(path.join(d, 'lib/tool.jar'));
  assert.equal(javaw(d, 'Tool.java').status, 0);
  const src = read(path.join(d, 'run-tool'));
  assert.ok(src.startsWith('#!/bin/sh\n# Generated by javaw. Regenerate with:\n#   javaw Tool.java\n'));
  assert.match(src, /^exec java "\$dir\/Tool.java" "\$@"$/m);
  assert.equal(fs.statSync(path.join(d, 'run-tool')).mode & 0o111, 0o111);
  for (const unused of ['-cp', 'bin/java', 'version', '-jar', '[[', 'readlink -f', 'realpath']) {
    assert.ok(!src.includes(unused), `unexpected ${unused}`);
  }

  const r = javaw(d, '--jar', 'lib/tool.jar', '--jvm-opts', '-Xmx64m -Dx=a', '--classpath', 'lib/*',
    '--java-home', '/opt/my jdk', '-o', 'out/');
  assert.equal(r.status, 0, r.stderr);
  const jar = read(path.join(d, 'out/run-tool'));
  assert.match(jar, /^# {3}javaw --jvm-opts '-Xmx64m -Dx=a' --classpath 'lib\/\*' --java-home '\/opt\/my jdk' -o out\/ --jar lib\/tool.jar$/m);
  assert.match(jar, /^exec '\/opt\/my jdk\/bin\/java' -Xmx64m -Dx=a -cp 'lib\/\*' -jar "\$dir\/..\/lib\/tool.jar" "\$@"$/m);
  for (const f of ['run-tool', 'out/run-tool']) assert.equal(run('sh', ['-n', path.join(d, f)]).status, 0);
});

test('output naming, several inputs, overwriting', () => {
  const d = tmp();
  touch(path.join(d, 'HTTPServer.java'));
  touch(path.join(d, 'Example1_Assert.java'));
  fs.mkdirSync(path.join(d, 'bin'));
  assert.equal(javaw(d, 'HTTPServer.java', 'Example1_Assert.java').status, 0);
  assert.ok(fs.existsSync(path.join(d, 'run-http-server')));
  assert.ok(fs.existsSync(path.join(d, 'run-example1-assert')));
  assert.equal(javaw(d, '-o', 'bin', 'HTTPServer.java', 'Example1_Assert.java').status, 0);
  assert.ok(fs.existsSync(path.join(d, 'bin/run-example1-assert')));
  assert.equal(javaw(d, '--output=sub/serve', 'HTTPServer.java').status, 0);
  assert.match(read(path.join(d, 'sub/serve')), /"\$dir\/..\/HTTPServer.java"/);
  assert.match(javaw(d, '-o', 'x', 'HTTPServer.java', 'Example1_Assert.java').stderr, /must be a directory/);

  const again = javaw(d, 'HTTPServer.java');
  assert.equal(again.status, 1);
  assert.match(again.stderr, /run-http-server: already exists \(use --force/);
  assert.equal(javaw(d, '--force', 'HTTPServer.java').status, 0);
  assert.match(read(path.join(d, 'run-http-server')), /# {3}javaw --force HTTPServer.java/);
});

test('--min-java parses versions and fails clearly', () => {
  const d = tmp();
  touch(path.join(d, 'Tool.java'));
  const check = (banner, min) => {
    const jdk = fakeJdk(fs.mkdtempSync(path.join(d, 'jdk-')), banner);
    const out = path.join(d, `w-${path.basename(jdk)}`);
    assert.equal(javaw(d, '--java-home', jdk, '--min-java', String(min), '-o', out, 'Tool.java').status, 0);
    return run(out, ['a b', 'c']);
  };
  const ok = check(['openjdk version "28-ea" 2027-03-23', 'OpenJDK Runtime'], 28);
  assert.equal(ok.status, 0, ok.stderr);
  assert.equal(ok.stdout, `[${d}/Tool.java][a b][c]\n`);
  assert.equal(check(['java version "1.8.0_392"'], 8).status, 0);
  assert.equal(check(['Picked up JAVA_TOOL_OPTIONS: -Dv="9"', 'openjdk version "17.0.2" 2022'], 17).status, 0);

  const old = check(['java version "1.8.0_392"'], 11);
  assert.equal(old.status, 1);
  assert.match(old.stderr, /^w-jdk-\w+: Java 11 or newer is required \(found: 1\.8\.0_392\)\n$/);
  const junk = check(['something else'], 11);
  assert.match(junk.stderr, /^w-jdk-\w+: Java 11 or newer is required \(found: no usable java\)\n$/);

  // A java home without java: same clear error, no shell error.
  assert.equal(javaw(d, '--java-home', path.join(d, 'none'), '--min-java', '11', '-o', 'w', 'Tool.java').status, 0);
  const missing = run(path.join(d, 'w'), []);
  assert.equal(missing.status, 1);
  assert.equal(missing.stderr, 'w: Java 11 or newer is required (found: no usable java)\n');
});

test('wrappers run Hello.java from anywhere', { skip: !has('java') && 'java not installed' }, () => {
  const d = tmp();
  const app = path.join(d, 'app');
  touch(path.join(app, 'Hello.java'), read(HELLO));
  assert.equal(javaw(app, '--min-java', '11', 'Hello.java').status, 0);
  const expect = (r, version = '1') => {
    assert.equal(r.stderr.replace(/^Picked up JAVA_TOOL_OPTIONS.*\n/, ''), '');
    assert.equal(r.stdout, `Hello a b|c (app.version=${version})\n`);
    assert.equal(r.status, 0);
  };
  fs.mkdirSync(path.join(d, 'elsewhere'));
  fs.mkdirSync(path.join(d, 'bin'));
  fs.symlinkSync('../app/run-hello', path.join(d, 'bin/hello'));           // relative
  fs.symlinkSync('hello', path.join(d, 'bin/hello2'));                     // chain of two
  fs.mkdirSync(path.join(d, 'decoy/app'), { recursive: true });

  expect(run(path.join(app, 'run-hello'), ['a b', 'c'], { cwd: path.join(d, 'elsewhere') }));
  expect(run(path.join(d, 'bin/hello'), ['a b', 'c'], { cwd: path.join(d, 'elsewhere') }));
  expect(run('../bin/hello2', ['a b', 'c'], { cwd: path.join(d, 'elsewhere') }));
  expect(run(path.join(app, 'run-hello'), ['a b', 'c'],
    { env: { ...process.env, JAVA_TOOL_OPTIONS: '-Dapp.version=2' } }), '2');
  expect(run('app/run-hello', ['a b', 'c'],
    { cwd: d, env: { ...process.env, CDPATH: path.join(d, 'decoy') } }));
  fs.symlinkSync('app', path.join(d, '-app'));                             // path starting with -
  expect(run('sh', ['--', '-app/run-hello', 'a b', 'c'], { cwd: d }));
  if (has('dash')) expect(run('dash', ['bin/hello2', 'a b', 'c'], { cwd: d }));

  // Moved and renamed together with its sibling.
  fs.renameSync(app, path.join(d, 'moved'));
  fs.renameSync(path.join(d, 'moved/run-hello'), path.join(d, 'moved/greet'));
  expect(run(path.join(d, 'moved/greet'), ['a b', 'c'], { cwd: path.join(d, 'elsewhere') }));
});

test('jar wrapper runs a real jar', { skip: !(has('javac') && has('jar')) && 'JDK tools not installed' }, () => {
  const d = tmp();
  assert.equal(run('javac', ['-d', path.join(d, 'classes'), HELLO]).status, 0);
  assert.equal(run('jar', ['--create', '--file', 'hello.jar', '--main-class', 'Hello', '-C', 'classes', '.'],
    { cwd: d }).status, 0);
  assert.equal(javaw(d, '--jar', 'hello.jar').status, 0);
  fs.mkdirSync(path.join(d, 'elsewhere'));
  const r = run(path.join(d, 'run-hello'), ['x'], { cwd: path.join(d, 'elsewhere') });
  assert.equal(r.stdout, 'Hello x (app.version=1)\n', r.stderr);
});
