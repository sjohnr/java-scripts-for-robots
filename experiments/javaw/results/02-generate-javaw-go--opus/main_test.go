func TestKebab(t *testing.T) {
	for in, want := range map[string]string{
		"FooBar": "foo-bar", "HTTPServer": "http-server", "Example1_Assert": "example1-assert",
		"Example1": "example1", "Foo__Bar": "foo-bar", "my-tool": "my-tool", "Tool": "tool",
		"tool": "tool", "my.app name": "my-app-name", "parseURLFast2Go": "parse-url-fast2-go",
	} {
		if got := kebab(in); got != want {
			t.Errorf("kebab(%q) = %q, want %q", in, got, want)
		}
	}
}

// javaw runs the tool in-process and returns exit code and combined output.
func javaw(args ...string) (int, string) {
	var out bytes.Buffer
	code := run(args, &out, &out)
	return code, out.String()
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestGenerate(t *testing.T) {
	t.Chdir(t.TempDir())
	if code, out := javaw("Tool.java"); code != 0 {
		t.Fatalf("exit %d: %s", code, out)
	}
	s := read(t, "run-tool")
	for _, want := range []string{"#!/bin/sh\n# Generated by: javaw Tool.java\n", `exec java "$dir/Tool.java" "$@"`} {
		if !strings.Contains(s, want) {
			t.Errorf("wrapper missing %q:\n%s", want, s)
		}
	}
	for _, unwanted := range []string{"-cp", "version", "[[", "readlink -f", "realpath"} {
		if strings.Contains(s, unwanted) {
			t.Errorf("minimal wrapper contains %q", unwanted)
		}
	}
	if st, _ := os.Stat("run-tool"); st.Mode()&0o111 == 0 {
		t.Errorf("not executable: %v", st.Mode())
	}
	if code, out := javaw("Tool.java"); code != 1 || !strings.Contains(out, "--force") {
		t.Errorf("overwrite should be refused, got %d: %s", code, out)
	}
	if code, out := javaw("--force", "--jar", "--classpath", "lib/*", "--java-home=/opt/my jdk",
		"--jvm-opts", "-Xmx1g -Da=b", "tool.jar"); code != 0 {
		t.Fatalf("exit %d: %s", code, out)
	}
	s = read(t, "run-tool")
	want := `exec '/opt/my jdk'/bin/java -Xmx1g -Da=b -cp 'lib/*' -jar "$dir/tool.jar" "$@"`
	if !strings.Contains(s, want) || !strings.Contains(s, "# Generated by: javaw --force --jar --classpath 'lib/*' '--java-home=/opt/my jdk'") {
		t.Errorf("unexpected wrapper:\n%s", s)
	}
}

func TestOutputs(t *testing.T) {
	t.Chdir(t.TempDir())
	os.Mkdir("out", 0o755)
	javaw("-o", "out", "FooBar.java", "HTTPServer.java")
	javaw("--output", "custom", "my-tool.jar")
	javaw("-o", "out/x", "Example1_Assert.java")
	for _, f := range []string{"out/run-foo-bar", "out/run-http-server", "custom", "out/x"} {
		if _, err := os.Stat(f); err != nil {
			t.Error(err)
		}
	}
	if code, out := javaw("-o", "nodir", "A.java", "B.java"); code != 2 || !strings.Contains(out, "must be a directory") {
		t.Errorf("got %d: %s", code, out)
	}
}

