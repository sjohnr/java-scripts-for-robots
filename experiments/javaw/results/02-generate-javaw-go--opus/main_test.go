// shells returns /bin/sh plus dash when installed, to catch non-POSIX constructs.
func shells() []string {
	s := []string{"/bin/sh"}
	if d, err := exec.LookPath("dash"); err == nil {
		s = append(s, d)
	}
	return s
}

func TestMinJava(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	fake := func(name, versionOutput string) {
		os.MkdirAll(name+"/bin", 0o755)
		script := "#!/bin/sh\nif [ \"$1\" = -version ]; then printf '" + versionOutput + "' >&2; exit 0; fi\necho ran \"$@\"\n"
		os.WriteFile(name+"/bin/java", []byte(script), 0o755)
	}
	fake("j8", `java version "1.8.0_292"\nJava(TM) SE Runtime Environment\n`)
	fake("j28", `Picked up JAVA_TOOL_OPTIONS: -Dx=1 version "1"\nopenjdk version "28-ea" 2027-03-23\n`)
	fake("junk", `something odd\n`)
	for _, tc := range []struct {
		home, min string
		ok        bool
	}{{"j8", "8", true}, {"j8", "11", false}, {"j28", "28", true}, {"j28", "29", false},
		{"junk", "8", false}, {"missing", "8", false}} {
		out := "run-" + tc.home + "-" + tc.min
		if code, msg := javaw("--java-home", filepath.Join(dir, tc.home), "--min-java", tc.min, "-o", out, "App.java"); code != 0 {
			t.Fatal(msg)
		}
		for _, sh := range shells() {
			b, err := exec.Command(sh, out, "x").CombinedOutput()
			got := string(b)
			if tc.ok && (err != nil || !strings.HasPrefix(got, "ran ")) {
				t.Errorf("%s %s: expected launch, got %v: %s", sh, out, err, got)
			}
			if !tc.ok && (err == nil || !strings.HasPrefix(got, out+": requires Java "+tc.min+" or newer (found: ") || strings.Count(got, "\n") != 1) {
				t.Errorf("%s %s: expected one clear error line, got %v: %q", sh, out, err, got)
			}
		}
	}
}

// TestWrappersRunJava runs the example program through generated wrappers in the ways that tend to break launchers.
func TestWrappersRunJava(t *testing.T) {
	if _, err := exec.LookPath("java"); err != nil {
		t.Skip("java not installed")
	}
	src, _ := filepath.Abs("examples/HelloWorld.java")
	root := t.TempDir()
	t.Chdir(root)
	for _, d := range []string{"app", "-app", "bin", "elsewhere", "decoy/app"} {
		os.MkdirAll(d, 0o755)
	}
	for _, d := range []string{"app", "-app"} {
		os.WriteFile(d+"/HelloWorld.java", []byte(read(t, src)), 0o644)
		if code, out := javaw("--min-java", "11", "-o", d+"/", "--", d+"/HelloWorld.java"); code != 0 {
			t.Fatal(out)
		}
	}
	os.Symlink("../app/run-hello-world", "bin/hello")
	os.Symlink("hello", "bin/hello2")
	runs := []struct {
		name, dir string
		env       []string
		cmd       []string
		want      string
	}{
		{"different directory", "elsewhere", nil, []string{"../app/run-hello-world", "a", "b"}, "Hello, a b! version=1"},
		{"relative symlink", "elsewhere", nil, []string{"../bin/hello", "x"}, "Hello, x! version=1"},
		{"symlink chain", "elsewhere", nil, []string{"../bin/hello2", "y"}, "Hello, y! version=1"},
		{"JAVA_TOOL_OPTIONS", "elsewhere", []string{"JAVA_TOOL_OPTIONS=-Dapp.version=2"}, []string{"../bin/hello2", "z"}, "Hello, z! version=2"},
		{"CDPATH", ".", []string{"CDPATH=" + filepath.Join(root, "decoy")}, []string{"app/run-hello-world", "c"}, "Hello, c! version=1"},
		{"path starting with -", ".", nil, []string{"/bin/sh", "--", "-app/run-hello-world", "d"}, "Hello, d! version=1"},
	}
	for _, r := range runs {
		cmd := exec.Command(r.cmd[0], r.cmd[1:]...)
		cmd.Dir, cmd.Env = r.dir, append(os.Environ(), r.env...)
		var stdout bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, os.Stderr
		if err := cmd.Run(); err != nil || strings.TrimSpace(stdout.String()) != r.want {
			t.Errorf("%s: got %v %q, want %q", r.name, err, stdout.String(), r.want)
		}
	}
}

func TestJarLaunch(t *testing.T) {
	_, e1 := exec.LookPath("javac")
	_, e2 := exec.LookPath("jar")
	if e1 != nil || e2 != nil {
		t.Skip("javac/jar not installed")
	}
	src, _ := filepath.Abs("examples/HelloWorld.java")
	t.Chdir(t.TempDir())
	for _, c := range [][]string{{"javac", "-d", "classes", src}, {"jar", "--create", "--file", "hello-world.jar", "--main-class", "HelloWorld", "-C", "classes", "."}} {
		if out, err := exec.Command(c[0], c[1:]...).CombinedOutput(); err != nil {
			t.Fatalf("%v: %s", err, out)
		}
	}
	javaw("--jar", "hello-world.jar")
	if out, err := exec.Command("./run-hello-world", "jar").Output(); err != nil || string(out) != "Hello, jar! version=1\n" {
		t.Errorf("got %v %q", err, out)
	}
}
