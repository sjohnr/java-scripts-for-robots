///usr/bin/env jbang "$0" "$@" ; exit $?
//JAVA 17+
//SOURCES javaw.java

import java.io.*;
import java.nio.file.*;
import java.util.*;

/** Unit tests for javaw plus end-to-end runs of generated wrappers. Run: jbang JavawTest.java */
class JavawTest {
    static int passed, failed;

    static void check(boolean ok, String what) {
        if (ok) passed++; else { failed++; System.out.println("FAIL: " + what); }
    }

    static void eq(Object expected, Object actual, String what) {
        check(Objects.equals(expected, actual), what + "\n  expected: " + expected + "\n  actual:   " + actual);
    }

    static void contains(String haystack, String needle, String what) {
        check(haystack.contains(needle), what + ": missing <" + needle + "> in\n" + haystack);
    }

    record Result(int code, String out, String err) {}

    static Result javaw(Path cwd, String... args) {
        var out = new ByteArrayOutputStream();
        var err = new ByteArrayOutputStream();
        int code = javaw.run(args, cwd, new PrintStream(out, true), new PrintStream(err, true));
        return new Result(code, out.toString(), err.toString());
    }

    /** Runs a shell command line in cwd with extra environment; returns exit code and combined output. */
    static Result sh(Path cwd, Map<String, String> env, String cmd) throws Exception {
        var pb = new ProcessBuilder("sh", "-c", cmd).directory(cwd.toFile()).redirectErrorStream(true);
        pb.environment().remove("JAVA_TOOL_OPTIONS");
        pb.environment().remove("CDPATH");
        pb.environment().putAll(env);
        Process p = pb.start();
        String out = new String(p.getInputStream().readAllBytes());
        return new Result(p.waitFor(), out, "");
    }

    public static void main(String[] args) throws Exception {
        kebabCase();
        cli();
        Path tmp = Files.createTempDirectory("javaw-test").toRealPath();
        generation(tmp.resolve("gen"));
        endToEnd(tmp.resolve("e2e"));
        System.out.println(passed + " passed, " + failed + " failed");
        System.exit(failed == 0 ? 0 : 1);
    }

    static void kebabCase() {
        String[][] cases = {
            {"Tool.java", "run-tool"}, {"tool.jar", "run-tool"}, {"FooBar.java", "run-foo-bar"},
            {"HTTPServer.java", "run-http-server"}, {"example1_assert.java", "run-example1-assert"},
            {"Example1.java", "run-example1"}, {"Foo__Bar.java", "run-foo-bar"}, {"my-tool.jar", "run-my-tool"},
            {"dir/My App.v2.jar", "run-my-app-v2"}, {"getHTTPResponseCode.java", "run-get-http-response-code"},
        };
        for (String[] c : cases) eq(c[1], javaw.defaultName(c[0]), "default name of " + c[0]);
        eq("plain/path.txt", javaw.shq("plain/path.txt"), "shq leaves safe words");
        eq("'it'\\''s $x'", javaw.shq("it's $x"), "shq quotes specials");
    }

    static void cli() throws IOException {
        Path cwd = Files.createTempDirectory("javaw-cli");
        Result r = javaw(cwd, "--help");
        eq(0, r.code, "--help exit code");
        contains(r.out, "Usage: javaw", "--help text");
        r = javaw(cwd, "--frobnicate", "Tool.java");
        eq(2, r.code, "unknown option exit code");
        contains(r.err, "unknown option: --frobnicate", "unknown option message");
        r = javaw(cwd);
        eq(2, r.code, "missing input exit code");
        contains(r.err, "missing input", "missing input message");
        contains(javaw(cwd, "Tool.java", "--classpath").err, "--classpath needs a value", "missing value");
        contains(javaw(cwd, "--min-java", "eleven", "T.java").err, "whole number", "bad --min-java");
        contains(javaw(cwd, "-o", "single", "A.java", "B.java").err, "must be a directory", "-o with several inputs");
        contains(javaw(cwd, "a/Tool.java", "b/Tool.java").err, "both be written", "duplicate output names");
        eq(List.of(), Arrays.asList(cwd.toFile().list()), "errors write nothing");
    }

    static void generation(Path dir) throws Exception {
        Files.createDirectories(dir);
        Result r = javaw(dir, "Tool.java");
        eq(0, r.code, "source wrapper exit code");
        Path w = dir.resolve("run-tool");
        String s = Files.readString(w);
        check(s.startsWith("#!/bin/sh\n# Generated by javaw"), "shebang and header comment");
        contains(s, "#   javaw Tool.java\n", "header records command");
        contains(s, "exec java \"$dir/Tool.java\" \"$@\"\n", "source launch line");
        check(!s.contains("version=") && !s.contains("-cp"), "minimal wrapper has no unused options");
        check(Files.isExecutable(w), "wrapper is executable");
        eq(0, sh(dir, Map.of(), "sh -n run-tool").code, "wrapper parses as sh");
        for (String bashism : List.of("[[", "<(", "function ", "local ", "readlink -f", "realpath"))
            check(!s.contains(bashism), "no " + bashism);

        r = javaw(dir, "Tool.java");
        eq(2, r.code, "refuses overwrite");
        contains(r.err, "--force", "overwrite hint");
        eq(0, javaw(dir, "--force", "Tool.java").code, "--force overwrites");

        javaw(dir, "--jar", "lib/my-tool.jar", "--classpath", "lib/*", "--jvm-opts", "-Xmx64m -Da=b",
              "--java-home", "/opt/j d/", "--min-java", "21");
        s = Files.readString(dir.resolve("run-my-tool"));
        contains(s, "#   javaw --classpath 'lib/*' --java-home '/opt/j d' --jvm-opts '-Xmx64m -Da=b' --min-java 21 --jar lib/my-tool.jar\n", "header is shell-quoted");
        contains(s, "exec '/opt/j d/bin/java' -Xmx64m -Da=b -cp 'lib/*' -jar \"$dir/lib/my-tool.jar\" \"$@\"\n", "jar launch line with options");
        contains(s, "version=$('/opt/j d/bin/java' -version", "version check uses --java-home java");
        contains(s, "-lt 21 ]", "min version");

        javaw(dir, "-o", "bin/", "A.java", "B.java");
        check(Files.exists(dir.resolve("bin/run-a")) && Files.exists(dir.resolve("bin/run-b")), "-o dir/ with several inputs");
        contains(Files.readString(dir.resolve("bin/run-a")), "\"$dir/../A.java\"", "program path is relative to wrapper");
        javaw(dir, "-o", "bin", "C.java");
        check(Files.exists(dir.resolve("bin/run-c")), "-o existing directory uses default name");
        javaw(dir, "--output", "bin/custom", "src/$weird\".java");
        contains(Files.readString(dir.resolve("bin/custom")), "\"$dir/../src/\\$weird\\\".java\"", "-o file name; special chars escaped");
    }

    static void endToEnd(Path root) throws Exception {
        Path app = Files.createDirectories(root.resolve("app"));
        Files.writeString(app.resolve("Hello.java"), """
            public class Hello {
                public static void main(String[] args) {
                    System.out.println("hello " + String.join("|", args) + " v" + System.getProperty("app.version", "1"));
                }
            }
            """);
        eq(0, javaw(app, "Hello.java").code, "generate run-hello");
        eq(0, javaw(app, "-o", "run-checked", "--min-java", "11", "Hello.java").code, "generate run-checked");
        Path other = Files.createDirectories(root.resolve("elsewhere"));
        String expected = "hello a|b c v1\n";

        eq(expected, sh(other, Map.of(), "../app/run-hello a 'b c'").out, "runs from a different directory");
        sh(other, Map.of(), "ln -s ../app/run-hello link1 && ln -s link1 link2");
        eq(expected, sh(other, Map.of(), "./link1 a 'b c'").out, "runs through a relative symlink");
        eq(expected, sh(root, Map.of(), "elsewhere/link2 a 'b c'").out, "runs through a chain of two symlinks");
        eq(expected, sh(root, Map.of(), other + "/link2 a 'b c'").out, "runs through absolute path to symlink chain");

        Result r = sh(other, Map.of("JAVA_TOOL_OPTIONS", "-Dapp.version=2"), "../app/run-checked a 'b c'");
        eq(0, r.code, "JAVA_TOOL_OPTIONS with --min-java exit code");
        contains(r.out, "hello a|b c v2\n", "JAVA_TOOL_OPTIONS reaches the program");

        // CDPATH: "app/run-hello" would make a naive `cd app` jump to decoy/app and print its path.
        Files.createDirectories(root.resolve("decoy/app"));
        eq(expected, sh(root, Map.of("CDPATH", root.resolve("decoy").toString()), "app/run-hello a 'b c'").out, "immune to exported CDPATH");

        // A $0 starting with "-" (exec'ing such a path directly makes sh parse it as an option, hence sh --).
        Files.createDirectories(root.resolve("-dash"));
        sh(root, Map.of(), "cp -- app/Hello.java app/run-hello -dash/ && mv -- -dash/run-hello -dash/renamed");
        eq(expected, sh(root, Map.of(), "sh -- -dash/renamed a 'b c'").out, "moved, renamed, $0 starting with -");
        sh(root, Map.of(), "ln -s -- -dash/renamed dashlink");
        eq(expected, sh(other, Map.of(), "../dashlink a 'b c'").out, "symlink target starting with -");

        javaw(app, "-o", "run-new", "--min-java", "999", "Hello.java");
        r = sh(other, Map.of(), "../app/run-new");
        eq(1, r.code, "too-old Java fails");
        contains(r.out, "error: Java 999 or newer is required (found: ", "too-old Java message");

        javaw(app, "-o", "run-nojava", "--min-java", "11", "--java-home", root.resolve("nope").toString(), "Hello.java");
        r = sh(other, Map.of(), "../app/run-nojava");
        eq("error: Java 11 or newer is required (found: none)\n", r.out, "missing java gives the same clear error");

        javaw(app, "-o", "run-home", "--min-java", "11", "--java-home", System.getProperty("java.home"), "Hello.java");
        eq(expected, sh(other, Map.of(), "../app/run-home a 'b c'").out, "--java-home runs that java");

        Path bin = Path.of(System.getProperty("java.home"), "bin");
        sh(app, Map.of(), bin.resolve("javac") + " -d classes Hello.java && "
            + bin.resolve("jar") + " --create --file hello-app.jar --main-class Hello -C classes .");
        javaw(app, "--jar", "hello-app.jar", "--jvm-opts", "-Dapp.version=3");
        eq("hello a|b c v3\n", sh(other, Map.of(), "../app/run-hello-app a 'b c'").out, "jar launch with --jvm-opts");

        fakeJava(root, app, other, "1.8.0_392", 8);
        fakeJava(root, app, other, "28-ea", 28);
    }

    /** A fake JDK whose java prints a noise line plus the given version: N passes, N+1 fails. */
    static void fakeJava(Path root, Path app, Path other, String version, int n) throws Exception {
        Path home = root.resolve("jdk-" + version), java = Files.createDirectories(home.resolve("bin")).resolve("java");
        Files.writeString(java, "#!/bin/sh\nprintf '%s\\n' 'Picked up JAVA_TOOL_OPTIONS: -Dx=1' "
            + "'openjdk version \"" + version + "\" 2027-03-23' >&2\n");
        java.toFile().setExecutable(true);
        for (int min : List.of(n, n + 1)) {
            javaw(app, "-o", "run-fake", "--force", "--min-java", "" + min, "--java-home", home.toString(), "Hello.java");
            Result r = sh(other, Map.of(), "../app/run-fake");
            if (min == n) eq(0, r.code, version + " satisfies --min-java " + n);
            else eq("error: Java " + min + " or newer is required (found: " + version + ")\n", r.out, version + " parsed as " + n);
        }
    }
}
